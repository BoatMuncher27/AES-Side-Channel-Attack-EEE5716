RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]


def _to_bytes(k):
    if isinstance(k, str):
        return list(bytes.fromhex(k))
    return [int(b) for b in k]


def expand_key(key):
    """AES-128 key schedule. Returns 11 round keys, each a list of 16 ints."""
    w = [_to_bytes(key)[4 * i:4 * i + 4] for i in range(4)]
    for i in range(4, 44):
        t = list(w[i - 1])
        if i % 4 == 0:
            t = [int(SBOX[b]) for b in t[1:] + t[:1]]
            t[0] ^= RCON[i // 4 - 1]
        w.append([a ^ b for a, b in zip(w[i - 4], t)])
    return [sum(w[4 * r:4 * r + 4], []) for r in range(11)]


def master_from_round10(k10):
    """Inverts the key schedule: last round key (16 bytes) -> master key (16 bytes)."""
    w = [None] * 44
    k10 = _to_bytes(k10)
    for i in range(4):
        w[40 + i] = k10[4 * i:4 * i + 4]
    for i in range(43, 3, -1):
        t = list(w[i - 1])
        if i % 4 == 0:
            t = [int(SBOX[b]) for b in t[1:] + t[:1]]
            t[0] ^= RCON[i // 4 - 1]
        w[i - 4] = [a ^ b for a, b in zip(w[i], t)]
    return bytes(sum(w[0:4], []))


def _xtime(a):
    return ((a << 1) ^ 0x1b) & 0xff if a & 0x80 else a << 1


def encrypt(pt, key):
    """Reference AES-128 encryption of one block (slow, for checking only)."""
    rk = expand_key(key)
    s = [p ^ k for p, k in zip(_to_bytes(pt), rk[0])]
    for r in range(1, 11):
        s = [int(SBOX[b]) for b in s]
        s = [s[(i + 4 * (i % 4)) % 16] for i in range(16)]           # ShiftRows
        if r != 10:                                                   # MixColumns
            out = []
            for c in range(4):
                a = s[4 * c:4 * c + 4]
                t = a[0] ^ a[1] ^ a[2] ^ a[3]
                out += [a[j] ^ t ^ _xtime(a[j] ^ a[(j + 1) % 4]) for j in range(4)]
            s = out
        s = [a ^ b for a, b in zip(s, rk[r])]
    return bytes(s)


